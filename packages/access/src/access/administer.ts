import type { Actor } from "../domain/Actor.ts";

/**
 * 운영 도구를 고칠 자격이 있는가.
 *
 * 테넌트와 계정과 멤버십처럼 **운영이 소유하는 것을 바꾸는 쓰기**가 이 판정을 지난다. 읽기는
 * 지나지 않는다.
 *
 * ## ⚠ 이 판정이 없으면 운영팀의 일반 구성원이 전권을 갖는다
 *
 * `canEnterApp` 은 문을 **테넌트 종류로만** 연다(INV-ACCESS-01). 종류는 「이 사람이 운영팀
 * 사람인가」에 답할 뿐이고 「무엇을 할 수 있는가」에는 답하지 않는다. 그래서 문만으로 쓰기를
 * 막으려 하면, 멤버십을 고칠 수 있는 사람이 자기를 아무 테넌트에나 넣어 그 문을 연다. 문을 여는
 * 축을 고치는 자리라서 권한 상승이 한 걸음에 끝난다.
 *
 * ## 자격은 둘을 함께 본다
 *
 * 운영 테넌트여야 하고 그 안에서 소유주나 관리자여야 한다. 종류를 다시 보는 까닭은 이 함수가
 * 한 앱만의 것이 아니기 때문이다. 문을 지났다는 사실을 판정이 전제하면, 다른 앱이 같은
 * 유스케이스를 부르게 되는 날 그 전제가 조용히 깨진다.
 *
 * ⚠ **플래그를 더하지 않는다.** `can_manage_tenancy` 같은 칸을 두면 역할과 플래그가 서로 다른 답을
 *    하는 상태가 생기고, 그때 어느 쪽이 정본인지 코드가 말하지 못한다.
 */
export const canAdministerOrg = (actor: Actor): boolean =>
    actor.tenantKind === "operator" && (actor.role === "owner" || actor.role === "admin");
