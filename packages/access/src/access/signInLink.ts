/**
 * 로그인 링크를 청하는 주소의 정본을 정한다.
 *
 * 운영이 먼저 세워 둔 사람에게는 `org.account` 행 하나만 있고 `auth.users` 는 아직 없다. 그 사람이
 * 처음 로그인하는 순간 같은 주소의 계정을 찾아 잇는다(INV-ACCESS-08).
 * 그래서 첫 로그인이 계정을 잇는 절차가 되고, 그 첫걸음이 사람이 적은 주소를 명부의 값에 맞추는 일이다.
 *
 * ⚠ **링크를 보낼지는 여기가 정하지 않는다.** 그 판정은 `canEnterApp` 하나가 답한다(INV-ACCESS-01).
 *    여기에 「고객사인가」나 「나간 사람인가」를 적으면 문을 여는 술어가 두 벌이 되고, 두 벌은 갈라진다.
 * ⚠ **명부가 소문자로 서 있다는 것에 기댄다.** `org.account.email` 에 소문자 유일 인덱스가 걸려 있어
 *    대문자만 다른 두 계정이 서지 못한다. 그 인덱스가 없으면 이 정규화가 여러 사람을 한 사람으로 읽는다.
 */

/**
 * 사람이 적은 주소를 명부와 대조할 값으로 접는다. 주소 꼴이 아니면 `null` 이고 조회를 지나지 않는다.
 *
 * ⚠ **주소가 실제로 있는지를 여기서 묻지 않는다.** 꼴을 보는 검사이고, 엄밀한 문법 검사도 아니다.
 *    RFC 를 흉내 내는 정규식은 멀쩡한 주소를 거절하면서 정작 막아야 할 것을 막지 못한다. 진짜 검사는
 *    그 주소로 보낸 편지가 닿는가이고, 그것을 여기서 대신할 수는 없다.
 */
export const normalizeLoginEmail = (raw: string): string | null =>
{
    const folded = raw.trim().toLowerCase();

    // 공백이 남아 있으면 주소가 아니다. 두 주소를 한 칸에 적은 것을 한 사람으로 읽지 않는다
    if (/\s/.test(folded))
    {
        return null;
    }

    const at = folded.indexOf("@");

    // 골뱅이가 없거나, 앞이 비었거나, 뒤가 비었거나, 둘 이상이면 보낼 곳을 고르지 못한다
    if (at <= 0 || at !== folded.lastIndexOf("@") || at === folded.length - 1)
    {
        return null;
    }

    return folded;
};
