/**
 * 로컬 계정으로 들어오는 길이 열려 있는가: 이 규칙의 **단 하나의 주인**이다.
 *
 * 종전에는 같은 판정이 두 곳에 있었다. 로그인 화면이 칸을 감출지 정하는 자리와(`login/_components/LoginPanel.tsx`)
 * 서버 액션이 스스로 거절하는 자리다(`actions/session.ts`). 둘이 갈라지는 날 화면은 감추는데 액션은 받는
 * 모양이 되고, 그것은 감춘 적이 없는 것과 같다. 그래서 한 함수가 답하고 두 자리가 그것을 읽는다.
 *
 * 여는 조건은 둘 가운데 하나다.
 *
 *   · 개발 환경이다: `npx turbo dev` 로 띄운 자리
 *   · `ALLOW_LOCAL_ACCOUNTS` 가 정확히 `"1"` 이다: 프로덕션 빌드를 상대로 e2e 를 돌리는 자리
 *
 * ⚠ **둘째 조건은 검사를 위한 자리이지 배포의 선택지가 아니다.** 프로덕션 빌드에서 로컬 계정 칸이 서는
 *    유일한 길이므로, 배포 환경변수에 이 이름이 들어가면 시드 계정으로 누구나 들어온다. 값을 `"1"` 로
 *    정확히 맞춘 것도 `true`·`yes` 같은 값이 실수로 걸리지 않게 하려는 것이다.
 * ⚠ **`NEXT_PUBLIC_` 을 붙이지 않는다.** 붙이면 빌드 때 클라이언트 번들에 박혀 배포된 자바스크립트가
 *    이 스위치의 존재를 광고한다. 서버에서만 읽는다.
 */
export const localAccountsAllowed = (): boolean =>
    process.env.NODE_ENV !== "production" || process.env["ALLOW_LOCAL_ACCOUNTS"] === "1";
